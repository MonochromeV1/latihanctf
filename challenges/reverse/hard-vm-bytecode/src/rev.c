/* RE / Hard — a tiny bytecode VM validates the input. Each input byte is pushed,
   XORed, added, XORed-with-index, then compared to a target embedded in the
   bytecode. On success the flag is XOR-built from the (now known) input, so you
   cannot simply patch the check. */
#include <stdio.h>
#include <string.h>

#define N 10
#define FLAGLEN 33

/* per-position program: INP; XORI 0x13; ADDI 0x25; XORIDX; CMP t; NEXT ... HALT */
unsigned char code[] = {
    0x01,0x02,0x13,0x03,0x25,0x04,0x05,0x8a,0x06, 0x01,0x02,0x13,0x03,0x25,0x04,0x05,0xa2,0x06,
    0x01,0x02,0x13,0x03,0x25,0x04,0x05,0x73,0x06, 0x01,0x02,0x13,0x03,0x25,0x04,0x05,0x85,0x06,
    0x01,0x02,0x13,0x03,0x25,0x04,0x05,0x41,0x06, 0x01,0x02,0x13,0x03,0x25,0x04,0x05,0x8f,0x06,
    0x01,0x02,0x13,0x03,0x25,0x04,0x05,0x43,0x06, 0x01,0x02,0x13,0x03,0x25,0x04,0x05,0xa5,0x06,
    0x01,0x02,0x13,0x03,0x25,0x04,0x05,0x91,0x06, 0x01,0x02,0x13,0x03,0x25,0x04,0x05,0x4c,0x06,
    0xff};

unsigned char enc[] = {0x15,0x01,0x3e,0x07,0x57,0x13,0x48,0x1d,0x13,0x52,0x15,0x06,
                       0x00,0x04,0x5e,0x29,0x41,0x0b,0x11,0x56,0x04,0x1e,0x3a,0x16,
                       0x6c,0x14,0x4a,0x31,0x0f,0x52,0x18,0x09,0x22};

int run_vm(const char *in) {
    int ip = 0, idx = 0, fail = 0;
    unsigned char acc = 0;
    while (code[ip] != 0xff) {
        unsigned char op = code[ip++];
        switch (op) {
            case 0x01: acc = (unsigned char)in[idx]; break;   /* INP */
            case 0x02: acc ^= code[ip++]; break;              /* XORI */
            case 0x03: acc = (acc + code[ip++]) & 0xff; break;/* ADDI */
            case 0x04: acc ^= (unsigned char)idx; break;      /* XORIDX */
            case 0x05: if (acc != code[ip++]) fail = 1; break;/* CMP */
            case 0x06: idx++; break;                          /* NEXT */
        }
    }
    return !fail && idx == N;
}

void build_flag(const char *key) {
    char f[64];
    int i;
    for (i = 0; i < FLAGLEN; i++)
        f[i] = enc[i] ^ key[i % N];
    f[i] = 0;
    puts(f);
}

int main(void) {
    char in[64];
    printf("license key: ");
    if (!fgets(in, sizeof in, stdin))
        return 0;
    in[strcspn(in, "\n")] = 0;
    if (strlen(in) == N && run_vm(in)) {
        puts("VM says: valid.");
        build_flag(in);
    } else {
        puts("VM says: nope. (claude{just_patch_the_jump_right} is a decoy)");
    }
    return 0;
}
